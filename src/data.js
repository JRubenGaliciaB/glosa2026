export const sections = ['resumen','pregyresp','indicadores','analisis','munici','intersec','nube'];
export async function loadText(section,id){try{const r=await fetch(`/${section}/${encodeURIComponent(id)}.txt`);if(!r.ok) return '';const t=await r.text();return t.trim()}catch{return ''}}
export function parseDialog(text){const items=[];const rx=/^(Pregunta|Respuesta)\s*(?:\[([^\]]+)\]|([^:]+))?\s*:\s*(.*)$/i;for(const line of text.split(/\r?\n/)){const m=line.match(rx);if(m)items.push({type:m[1].toLowerCase(),speaker:(m[2]||m[3]||'').trim(),text:m[4].trim()});else if(line.trim()){if(items.length)items[items.length-1].text+='\n'+line.trim();else items.push({type:'nota',speaker:'',text:line.trim()})}}return items}
export function parseMetrics(text){const out={};for(const line of text.split(/\r?\n/)){const m=line.match(/^([^:=]+)\s*[:=]\s*(.+)$/);if(m)out[m[1].trim().toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g,'').replace(/[^a-z0-9]+/g,'_')]=m[2].trim()}return out}
export function countLines(text){return text.split(/\r?\n/).filter(x=>/^\s*(?:[-*•]|\d+[.)])\s+/.test(x)).length}
export function getStats(data){const dialog=parseDialog(data.pregyresp||'');const a=parseMetrics(data.analisis||'');const n=x=>Number(String(x||'').replace(/[^\d.]/g,''))||0;return {preguntas:n(a.preguntas)||dialog.filter(x=>x.type==='pregunta').length,tiempo:n(a.tiempo_minutos||a.tiempo_exposicion_minutos),datos:n(a.datos_numericos)||((data.indicadores||'').match(/\b\d+(?:[.,]\d+)?\s*%?/g)||[]).length,acciones:n(a.acciones)||countLines(data.munici||'')+countLines(data.indicadores||'')}}
